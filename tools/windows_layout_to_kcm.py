"""Convert a Windows keyboard layout into an Android .kcm overlay, key by key.

Asks Windows itself (ToUnicodeEx) what every key produces with no modifier, Shift, AltGr and
Caps Lock, including dead keys (accents), so the Android layout behaves exactly like the PC.

    python windows_layout_to_kcm.py                      # active layout -> layout.kcm
    python windows_layout_to_kcm.py 00010416 abnt2.kcm   # Portuguese (Brazil ABNT2)
    python windows_layout_to_kcm.py --remote rdp.kcm     # remote-desktop variant

--remote: dead keys produce no character on Android. Remote desktop clients (Windows App,
RustDesk...) then send the key's scan code, and the remote Windows composes the accent itself.
Without it the client sends the bare accent and you get "´a" instead of "á". Accents typed with
the physical keyboard in local Android apps stop working with this variant.

Layout ids (KLID) live in HKLM\\SYSTEM\\CurrentControlSet\\Control\\Keyboard Layouts.
"""
import ctypes
import ctypes.wintypes as wt
import sys

u = ctypes.WinDLL("user32")
u.LoadKeyboardLayoutW.restype = wt.HKL
u.GetKeyboardLayoutNameW.argtypes = [wt.LPWSTR]
u.MapVirtualKeyExW.argtypes = [wt.UINT, wt.UINT, wt.HKL]
u.ToUnicodeEx.argtypes = [wt.UINT, wt.UINT, ctypes.c_char_p, wt.LPWSTR, ctypes.c_int, wt.UINT, wt.HKL]

# PC scan code (set 1) -> Android key code name (AOSP Generic.kl)
SCANCODES = {
    0x29: "GRAVE", 0x02: "1", 0x03: "2", 0x04: "3", 0x05: "4", 0x06: "5", 0x07: "6", 0x08: "7", 0x09: "8",
    0x0A: "9", 0x0B: "0", 0x0C: "MINUS", 0x0D: "EQUALS",
    0x10: "Q", 0x11: "W", 0x12: "E", 0x13: "R", 0x14: "T", 0x15: "Y", 0x16: "U", 0x17: "I", 0x18: "O", 0x19: "P",
    0x1A: "LEFT_BRACKET", 0x1B: "RIGHT_BRACKET", 0x2B: "BACKSLASH",
    0x1E: "A", 0x1F: "S", 0x20: "D", 0x21: "F", 0x22: "G", 0x23: "H", 0x24: "J", 0x25: "K", 0x26: "L",
    0x27: "SEMICOLON", 0x28: "APOSTROPHE",
    0x2C: "Z", 0x2D: "X", 0x2E: "C", 0x2F: "V", 0x30: "B", 0x31: "N", 0x32: "M", 0x33: "COMMA", 0x34: "PERIOD",
    0x35: "SLASH", 0x73: "RO",
}
# Windows dead key -> Android combining accent
DEAD = {"´": "\\u0301", "`": "\\u0300", "~": "\\u0303", "^": "\\u0302", "¨": "\\u0308"}
VK_SHIFT, VK_CONTROL, VK_MENU, VK_CAPITAL, VK_DECIMAL = 0x10, 0x11, 0x12, 0x14, 0x6E


def to_char(hkl, vk, sc, shift=False, altgr=False, caps=False):
    st = (ctypes.c_ubyte * 256)()
    if shift:
        st[VK_SHIFT] = 0x80
    if altgr:
        st[VK_CONTROL] = st[VK_MENU] = 0x80
    if caps:
        st[VK_CAPITAL] = 0x01
    buf = ctypes.create_unicode_buffer(8)
    n = u.ToUnicodeEx(vk, sc, ctypes.cast(st, ctypes.c_char_p), buf, 8, 0, hkl)
    if n < 0:  # dead key: press it again to clear the pending accent
        u.ToUnicodeEx(vk, sc, ctypes.cast((ctypes.c_ubyte * 256)(), ctypes.c_char_p),
                      ctypes.create_unicode_buffer(8), 8, 0, hkl)
        return ("dead", buf.value[:1])
    if n == 1 and buf.value >= " ":
        return ("char", buf.value[0])
    return None


def literal(r, remote=False):
    kind, c = r
    if kind == "dead":
        return "none" if remote else f"'{DEAD.get(c, c)}'"
    if c in "'\\":
        return f"'\\{c}'"
    if ord(c) > 0x7E:
        return f"'\\u{ord(c):04x}'"
    return f"'{c}'"


def convert(klid, remote=False):
    hkl = u.LoadKeyboardLayoutW(klid, 0)
    variant = " (remote desktop variant)" if remote else ""
    out = [f"# Generated by LogiSync tools/windows_layout_to_kcm.py from Windows layout {klid}{variant}",
           "type OVERLAY", ""]
    lit = lambda r: literal(r, remote)
    pad = " " * 4
    for sc, name in SCANCODES.items():
        vk = u.MapVirtualKeyExW(sc, 1, hkl)  # MAPVK_VSC_TO_VK
        base, shift = to_char(hkl, vk, sc), to_char(hkl, vk, sc, shift=True)
        altgr, caps = to_char(hkl, vk, sc, altgr=True), to_char(hkl, vk, sc, caps=True)
        if not (base or shift or altgr):
            continue
        out.append(f"key {name} {{")
        letter = base and base[0] == "char" and caps and caps != base and caps == shift
        if letter:
            out.append(f"{pad}{'label:':<36}{lit(shift)}")
        if base:
            out.append(f"{pad}{'base:':<36}{lit(base)}")
        if shift:
            out.append(f"{pad}{'shift, capslock:' if letter else 'shift:':<36}{lit(shift)}")
        if altgr:
            out.append(f"{pad}{'ralt:':<36}{lit(altgr)}")
        out.append("}\n")
    dec = to_char(hkl, VK_DECIMAL, 0x53)
    if dec and dec[1] != ".":
        out.append(f"key NUMPAD_DOT {{\n{pad}{'label:':<36}{literal(dec)}\n{pad}{'base:':<36}fallback FORWARD_DEL\n"
                   f"{pad}{'numlock:':<36}{literal(dec)}\n}}\n")
    return "\n".join(out)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--remote"]
    remote = "--remote" in sys.argv
    if args and len(args[0]) == 8:
        klid = args[0]
        dest = args[1] if len(args) > 1 else "layout.kcm"
    else:
        name = ctypes.create_unicode_buffer(9)
        u.GetKeyboardLayoutNameW(name)
        klid = name.value
        dest = args[0] if args else "layout.kcm"
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(convert(klid, remote))
    print(f"{klid} -> {dest}")
